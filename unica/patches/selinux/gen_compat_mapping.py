"""Synthesize a sepolicy mapping file for a vendor API the system no longer ships.

Newer system images drop old mapping files (e.g. One UI 9 has no 30.0.cil), which
makes init fail to compile the split policy on Android 11 vendors. Derive the
missing mapping from the oldest one still shipped by renaming its version suffix,
keep only statements whose versioned attributes the vendor actually declares,
and map any remaining vendor attribute to the same-named platform type.

usage: gen_compat_mapping.py <base.cil> <out.cil> <base_ver> <vendor_ver>
                             <plat_pub_versioned.cil> [platform policy .cil ...]
"""
import re
import sys


def ver_tag(ver):
    return "_" + ver.replace(".", "_")


def main():
    base, out, base_ver, ver, pub = sys.argv[1:6]
    platform = sys.argv[6:]
    old, new = ver_tag(base_ver), ver_tag(ver)
    token = re.compile(r"[A-Za-z0-9_]+" + re.escape(new) + r"\b")

    with open(pub, encoding="utf-8", errors="replace") as f:
        declared = set(token.findall(f.read()))

    platform_types = set()
    for path in platform:
        with open(path, encoding="utf-8", errors="replace") as f:
            platform_types.update(re.findall(r"^\((?:type|typeattribute) ([A-Za-z0-9_]+)\)", f.read(), re.M))

    kept, dropped, mapped = [], 0, set()
    with open(base, encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.replace(old, new)
            used = token.findall(line)
            if used and not all(t in declared for t in used):
                dropped += 1
                continue
            kept.append(line if line.endswith("\n") else line + "\n")
            m = re.match(r"\s*\(typeattributeset ([A-Za-z0-9_]+)", line)
            if m:
                mapped.add(m.group(1))

    added, unmapped = 0, []
    if platform:
        for attr in sorted(declared - mapped):
            plain = attr[: -len(new)]
            if plain in platform_types:
                kept.append("(expandtypeattribute (%s) true)\n" % attr)
                kept.append("(typeattributeset %s (%s))\n" % (attr, plain))
                added += 1
            else:
                unmapped.append(attr)

    with open(out, "w", encoding="utf-8") as f:
        f.write(";; Generated by UN1CA from %s mapping for vendor %s\n" % (base_ver, ver))
        f.writelines(kept)

    print("kept=%d dropped=%d added=%d unmapped=%d" % (len(kept), dropped, added, len(unmapped)))
    if unmapped:
        print("unmapped: " + " ".join(unmapped[:40]) + (" ..." if len(unmapped) > 40 else ""))


if __name__ == "__main__":
    main()
