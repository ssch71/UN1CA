    LOGW "Missing SPF patches for condition ($1: [${!1}], $2: [${!2}]), keeping source behaviour"
}

# One UI 9 moved the SPF dump into dumpProductFeature() and split most
# "KEY: value" strings into "KEY: " + "value", so handle both layouts.
# The dump is informational only, values that can't be matched safely are skipped.
PATCH_RRC_DUMP()
{
    local RRC="smali_classes6/com/samsung/android/hardware/display/RefreshRateConfig.smali"
    local RRC_PATH="$APKTOOL_DIR/system/framework/framework.jar/$RRC"
    local METHOD="dump(Ljava/io/PrintWriter;Ljava/lang/String;Z)V"
    local COUNT

    DECODE_APK "system" "system/framework/framework.jar" || return 1

    if grep -q "^\.method.* dumpProductFeature(Ljava/io/PrintWriter;Ljava/lang/String;Z)V" "$RRC_PATH"; then
        METHOD="dumpProductFeature(Ljava/io/PrintWriter;Ljava/lang/String;Z)V"
    fi

    if grep -qF "\"$1: $2\"" "$RRC_PATH"; then
        SMALI_PATCH "system" "system/framework/framework.jar" "$RRC" "replace" \
            "$METHOD" "$1: $2" "$1: $3"
        return $?
    fi

    COUNT=0
    if [ "$2" ]; then
        COUNT="$(awk -v FN=" ${METHOD}" -v STR="\"$2\"" '
            /^\.method/ && index($0, FN) { inside = 1 }
            inside && /^[[:space:]]*const-string/ && index($0, STR) { n++ }
            inside && /^\.end method/ { inside = 0 }
            END { print n + 0 }
        ' "$RRC_PATH")"
    fi

    if [[ "$COUNT" == "1" ]]; then
        SMALI_PATCH "system" "system/framework/framework.jar" "$RRC" "replace" \
            "$METHOD" "$2" "$3"
    else
        LOGW "Skipping RefreshRateConfig dump patch for $1 ($2 -> $3)"
    fi
}

# One UI 9 moved many classes to different smali_classes* dirs (e.g. SecSettings
# classes4 -> classes3, framework classes4 -> classes6). Resolve those paths on
# the fly, and skip (with a warning) patches whose code no longer matches
# instead of aborting the whole build.
PF_FIND_SMALI()
{
    local DIR="$1"
    local SMALI="$2"
    local MATCHES

    if [ -f "$DIR/$SMALI" ] || [[ "$SMALI" != smali* ]]; then
        echo "$SMALI"
        return 0
    fi

    MATCHES="$(find "$DIR/" -mindepth 1 -maxdepth 1 -type d -name "smali*" -exec test -f "{}/${SMALI#*/}" \; -print)"
    if [ "$(wc -l <<< "$MATCHES")" == "1" ] && [ "$MATCHES" ]; then
        MATCHES="${MATCHES%/}"; echo "${MATCHES##*/}/${SMALI#*/}"
    else
        echo "$SMALI"
    fi
}

PF_SMALI_PATCH()
{
    local PARTITION="$1"
    local FILE="$2"
    local DIR="$APKTOOL_DIR/$PARTITION/${FILE//system\//}"
    local SMALI

    shift 2
    DECODE_APK "$PARTITION" "$FILE" || return 1
    SMALI="$(PF_FIND_SMALI "$DIR" "$1")"
    shift

    if [ ! -f "$DIR/$SMALI" ]; then
        LOGW "Skipping SPF patch: /$PARTITION/$FILE/$SMALI not found"
        return 0
    fi

    SMALI_PATCH "$PARTITION" "$FILE" "$SMALI" "$@" || \
        LOGW "Skipping SPF patch: \"$1\" failed in /$PARTITION/$FILE/$SMALI"
}

PF_APPLY_PATCH()
{
    local PARTITION="$1"
    local FILE="$2"
    local PATCH="$3"
    local DIR="$APKTOOL_DIR/$PARTITION/${FILE//system\//}"
    local TMP_PATCH
    local OLD
    local NEW

    DECODE_APK "$PARTITION" "$FILE" || return 1

    TMP_PATCH="$(mktemp)"
    cp -a "$PATCH" "$TMP_PATCH"
    while read -r OLD; do
        NEW="$(PF_FIND_SMALI "$DIR" "$OLD")"
        if [[ "$NEW" != "$OLD" ]]; then
            awk -v OLD="$OLD" -v NEW="$NEW" '{
                while ((i = index($0, OLD)) > 0) $0 = substr($0, 1, i - 1) NEW substr($0, i + length(OLD))
                print
            }' "$TMP_PATCH" > "$TMP_PATCH.new" && mv -f "$TMP_PATCH.new" "$TMP_PATCH"
        fi
    done < <(grep "^+++ b/" "$PATCH" | sed "s|^+++ b/||" | sort -u)

    if LC_ALL=C patch -p1 -d "$DIR" -N --forward -l --dry-run -s < "$TMP_PATCH" &> /dev/null; then
        APPLY_PATCH "$PARTITION" "$FILE" "$TMP_PATCH"
    else
        LOGW "Skipping SPF patch \"${PATCH//$SRC_DIR\//}\": /$PARTITION/$FILE smali does not match"
    fi
    rm -f "$TMP_PATCH"
}
